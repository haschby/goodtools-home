@pytest.mark.asyncio
async def test_get_all_returns_persisted_buybacks(client):
    payload = [
        {"gc_booking": "B-123", "amount": 100, "currency": "EUR"},
        {"gc_booking": "B-456", "amount": 200, "currency": "EUR"},
    ]
    create_resp = await client.post("/client/buyback/creates", json=payload)
    assert create_resp.status_code == 201

    resp = await client.get("/client/buyback/all")

    assert resp.status_code == 201
    body = resp.json()
    assert body["status_code"] == 201
    items = body["data"]["items"]
    assert len(items) == 2
    assert body["data"]["total"] == 2
    amounts = sorted(item["amount"] for item in items)
    assert amounts == [100, 200]
    for item in items:
        assert item["id"]
        assert item["created_at"]


async def _seed_buyback(session_factory, *, file_path=None) -> str:
    """Insert a buyback directly and return its generated id."""
    from domain.models.buyback import Buyback
    from domain.models.enums import StatusBuyBackEnum

    buyback = Buyback(
        amount=150,
        status=StatusBuyBackEnum.TO_BE_TRAITED.value,
        gc_booking="B-999",
        file_path=file_path,
    )
    async with session_factory() as session:
        async with session.begin():
            session.add(buyback)
        await session.refresh(buyback)
        return buyback.id


@pytest.mark.asyncio
async def test_get_by_id_without_document_returns_200_and_no_url(
    client, session_factory
):
    buyback_id = await _seed_buyback(session_factory, file_path=None)

    resp = await client.get(f"/client/buyback/{buyback_id}")

    assert resp.status_code == 200
    body = resp.json()
    assert body["status_code"] == 200
    assert body["data"]["id"] == buyback_id
    assert body["data"]["document"] is None


@pytest.mark.asyncio
async def test_get_by_id_with_document_returns_presigned_url(
    client, session_factory
):
    storage_key = "buyback/some-file.pdf"
    buyback_id = await _seed_buyback(session_factory, file_path=storage_key)

    resp = await client.get(f"/client/buyback/{buyback_id}")

    assert resp.status_code == 200
    body = resp.json()
    assert body["status_code"] == 200
    document = body["data"]["document"]
    assert document is not None
    assert document["storage_key"] == storage_key
    assert document["url"] == f"https://storage.test/{storage_key}?sig=abc"


