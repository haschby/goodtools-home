@pytest_asyncio.fixture
async def client(session_factory):
    """Boots a minimal FastAPI app wired against the in-memory test database.

    The real AppContainer is used (providers are lazy, so no external resource
    is initialised), but its buyback sub-container is overridden to use the
    in-memory SQLite session factory and a fake storage strategy.
    """
    test_buyback_container = BuybackContainer(
        session=session_factory,
        storage=FakeStorage(),
    )

    container = AppContainer()
    container.buyback_container.override(test_buyback_container)

    app = FastAPI()
    app.include_router(buyback_route_module.buyback_routes())

    container.wire(modules=[buyback_route_module])

    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as ac:
        yield ac

    container.buyback_container.reset_override()
    container.unwire()


@pytest.mark.asyncio
async def test_post_creates_persists_and_returns_buybacks(client):
    payload = [
        {"gc_booking": "B-123", "amount": 100, "currency": "EUR"},
        {"gc_booking": "B-456", "amount": 200, "currency": "EUR"},
    ]

    resp = await client.post("/client/buyback/creates", json=payload)

    assert resp.status_code == 201
    body = resp.json()
    assert body["status_code"] == 201
    assert len(body["data"]) == 2

    amounts = sorted(item["amount"] for item in body["data"])
    assert amounts == [100, 200]
    for item in body["data"]:
        assert item["id"]  # generated by the DB layer
        assert item["created_at"]


